// Returns the message for the request's language, filling in {placeholders} from params
function t(req, key, params = {}) {
    const language = messages[req.get("X-Language")] ? req.get("X-Language") : "en";
    const text = messages[language][key] ?? messages.en[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

module.exports = { t, messages };
